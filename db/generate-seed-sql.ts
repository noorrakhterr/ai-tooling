/**
 * One-off script: generates db/002_seed_data.sql from the current
 * src/data/tools.ts and src/data/recordings.ts arrays, so the seed SQL
 * can't drift from what's actually in the TypeScript source. Run with:
 *   npx tsx db/generate-seed-sql.ts
 * Not part of the app build — a migration helper only.
 */
import { writeFileSync } from 'node:fs'
import { TOOLS } from '../src/data/tools'
import { RECORDINGS } from '../src/data/recordings'

function sqlString(value: string | undefined): string {
  if (value === undefined) return 'NULL'
  return `'${value.replace(/'/g, "''")}'`
}

function sqlStringArray(values: string[]): string {
  if (values.length === 0) return "'{}'"
  const escaped = values.map((v) => v.replace(/"/g, '\\"'))
  return `'{${escaped.map((v) => `"${v}"`).join(',')}}'`
}

function sqlBool(value: boolean | undefined): string {
  return value ? 'true' : 'false'
}

const toolRows = TOOLS.map(
  (tool) =>
    `  (${sqlString(tool.name)}, ${sqlString(tool.type)}, ${sqlString(tool.description)}, ${sqlString(tool.link)}, ${sqlStringArray(tool.phaseIds)}, ${sqlString(tool.owner)}, ${sqlBool(tool.comingSoon)})`,
).join(',\n')

const recordingRows = RECORDINGS.map(
  (recording) =>
    `  (${sqlString(recording.title)}, ${sqlString(recording.link)}, ${sqlString(recording.customer)}, ${sqlString(recording.owner)}, ${sqlString(recording.callDate)}::date, ${sqlStringArray(recording.labels)}, ${sqlString(recording.transcript)})`,
).join(',\n')

const sql = `-- Generated by db/generate-seed-sql.ts from src/data/tools.ts and
-- src/data/recordings.ts. Run via the OAP dashboard SQL editor AFTER
-- 001_create_ai_tools_and_gong_recordings.sql. Re-running this will
-- duplicate rows — only run once against a fresh table.

INSERT INTO ai_tools (name, type, description, link, "phaseIds", owner, "comingSoon") VALUES
${toolRows};

INSERT INTO gong_recordings (title, link, customer, owner, "callDate", labels, transcript) VALUES
${recordingRows};
`

writeFileSync(new URL('./002_seed_data.sql', import.meta.url), sql)
console.log(`Wrote db/002_seed_data.sql (${TOOLS.length} tools, ${RECORDINGS.length} recordings)`)
